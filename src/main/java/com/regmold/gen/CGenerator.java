package com.regmold.gen;

import com.regmold.domain.Access;
import com.regmold.domain.Field;
import com.regmold.domain.Model;
import com.regmold.domain.Register;

import java.util.ArrayList;
import java.util.List;

/** Generates a standalone C access layer. All write masks/sequences carry the model
 *  version in header comments so generated code traces back to the mold revision. */
public final class CGenerator {

    private CGenerator() {
    }

    public static List<GenFile> generate(Model model, String modelHash) {
        String pfx = Naming.snake(model.name());
        return List.of(
                new GenFile("c/inc/" + pfx + "_regs.h", header(model, pfx, modelHash)),
                new GenFile("c/src/" + pfx + "_regs.c", source(model, pfx, modelHash)));
    }

    private static String banner(Model model, String hash) {
        return "/*\n"
                + " * " + model.name() + " register access layer\n"
                + " * Generated by register-mold. DO NOT EDIT.\n"
                + " * model:    " + model.name() + " version " + model.version() + "\n"
                + " * sha256:   " + hash + "\n"
                + " * revision: " + model.revisionId() + "\n"
                + " */\n";
    }

    private static String header(Model model, String pfx, String hash) {
        StringBuilder sb = new StringBuilder(banner(model, hash));
        sb.append("#ifndef ").append(pfx.toUpperCase()).append("_REGS_H\n");
        sb.append("#define ").append(pfx.toUpperCase()).append("_REGS_H\n\n");
        sb.append("#include <stdint.h>\n\n");
        sb.append("#ifdef __cplusplus\n");
        sb.append("extern \"C\" {\n");
        sb.append("#endif\n\n");
        sb.append("#define ").append(pfx.toUpperCase()).append("_MODEL_HASH \"").append(hash).append("\"\n");
        sb.append("#define ").append(pfx.toUpperCase()).append("_MODEL_VERSION \"")
                .append(model.version()).append("\"\n");
        sb.append("#define ").append(pfx.toUpperCase()).append("_WORD_BYTES ").append(model.wordBytes()).append("\n\n");

        sb.append("/* ---- bus hooks: supplied by the platform ---- */\n");
        sb.append("uint32_t ").append(pfx).append("_bus_read32(uint64_t addr);\n");
        sb.append("void ").append(pfx).append("_bus_write32(uint64_t addr, uint32_t data);\n");
        sb.append("uint64_t ").append(pfx).append("_bus_read64(uint64_t addr);\n");
        sb.append("void ").append(pfx).append("_bus_write64(uint64_t addr, uint64_t data);\n\n");

        for (Register r : model.registers()) {
            String rs = pfx.toUpperCase() + "_" + Naming.upper(r.name());
            sb.append("/* ").append(r.name()).append(" @ 0x")
                    .append(Long.toUnsignedString(r.address(), 16)).append(" */\n");
            sb.append("#define ").append(rs).append("_ADDR UINT64_C(0x")
                    .append(Long.toUnsignedString(r.address(), 16)).append(")\n");
            sb.append("#define ").append(rs).append("_WIDTH_BITS ").append(r.widthBits()).append("\n");
            if (r.isAlias()) {
                sb.append("#define ").append(rs).append("_ALIAS_OF \"").append(r.aliasOf()).append("\"\n");
            }
            for (Field f : r.fields()) {
                String fs = rs + "_" + Naming.upper(f.name());
                sb.append("#define ").append(fs).append("_SHIFT ").append(f.lsb()).append("u\n");
                sb.append("#define ").append(fs).append("_WIDTH ").append(f.width()).append("u\n");
                sb.append("#define ").append(fs).append("_MASK UINT64_C(0x")
                        .append(Long.toUnsignedString(f.mask(), 16)).append(")\n");
                sb.append("#define ").append(fs).append("_RESET UINT64_C(0x")
                        .append(Long.toUnsignedString(f.reset(), 16)).append(")\n");
            }
            if (r.widthBits() > 32) {
                sb.append("uint64_t ").append(pfx).append("_").append(Naming.snake(r.name()))
                        .append("_read(void);\n");
                sb.append("void ").append(pfx).append("_").append(Naming.snake(r.name()))
                        .append("_write(uint64_t value);\n");
            } else {
                sb.append("uint32_t ").append(pfx).append("_").append(Naming.snake(r.name()))
                        .append("_read(void);\n");
                sb.append("void ").append(pfx).append("_").append(Naming.snake(r.name()))
                        .append("_write(uint32_t value);\n");
            }
            sb.append("void ").append(pfx).append("_").append(Naming.snake(r.name()))
                    .append("_set(uint64_t mask);\n");
            sb.append("void ").append(pfx).append("_").append(Naming.snake(r.name()))
                    .append("_clear(uint64_t mask);\n\n");
        }

        sb.append("#ifdef __cplusplus\n");
        sb.append("}\n");
        sb.append("#endif\n\n");
        sb.append("#endif\n");
        return sb.toString();
    }

    private static String source(Model model, String pfx, String hash) {
        StringBuilder sb = new StringBuilder(banner(model, hash));
        sb.append("#include \"").append(pfx).append("_regs.h\"\n\n");

        for (Register r : model.registers()) {
            String sn = Naming.snake(r.name());
            String addr = pfx.toUpperCase() + "_" + Naming.upper(r.name()) + "_ADDR";
            sb.append("/* ").append(r.name());
            if (r.isAlias()) {
                sb.append(" (alias of ").append(r.aliasOf()).append(")");
            }
            sb.append(" */\n");
            boolean wide = r.widthBits() > 32;
            String ret = wide ? "uint64_t" : "uint32_t";
            String arg = wide ? "uint64_t value" : "uint32_t value";
            sb.append(ret).append(" ").append(pfx).append("_").append(sn).append("_read(void)\n{\n");
            sb.append("    return ").append(wide ? pfx + "_bus_read64(" : pfx + "_bus_read32(")
                    .append(addr).append(");\n}\n\n");
            sb.append("void ").append(pfx).append("_").append(sn).append("_write(").append(arg).append(")\n{\n");
            if (r.access() == Access.W1S || policyOnlyW1S(r)) {
                sb.append("    /* atomic write-one-to-set port */\n");
                sb.append("    ").append(wide ? pfx + "_bus_write64(" : pfx + "_bus_write32(")
                        .append(addr).append(", value);\n");
            } else if (r.access() == Access.W1C || policyOnlyW1C(r)) {
                sb.append("    /* atomic write-one-to-clear port */\n");
                sb.append("    ").append(wide ? pfx + "_bus_write64(" : pfx + "_bus_write32(")
                        .append(addr).append(", value);\n");
            } else {
                sb.append("    ").append(wide ? pfx + "_bus_write64(" : pfx + "_bus_write32(")
                        .append(addr).append(", value);\n");
            }
            sb.append("}\n\n");

            sb.append("void ").append(pfx).append("_").append(sn).append("_set(uint64_t mask)\n{\n");
            String setPort = findPort(model, r, Access.W1S);
            if (setPort != null) {
                sb.append("    /* atomic set via ").append(setPort).append(" (write-one-to-set) */\n");
                sb.append("    ").append(r.widthBits() > 32 ? pfx + "_bus_write64(" : pfx + "_bus_write32(")
                        .append(pfx.toUpperCase()).append("_").append(Naming.upper(setPort)).append("_ADDR, ")
                        .append(wide64(r)).append("mask);\n");
            } else {
                sb.append("    /* read-modify-write set (single bus entry: set) */\n");
                sb.append("    ").append(wide ? "uint64_t" : "uint32_t").append(" cur = ")
                        .append(pfx).append("_").append(sn).append("_read();\n");
                sb.append("    ").append(pfx).append("_").append(sn).append("_write(cur | (")
                        .append(wide ? "" : "(uint32_t)").append("mask));\n");
            }
            sb.append("}\n\n");

            sb.append("void ").append(pfx).append("_").append(sn).append("_clear(uint64_t mask)\n{\n");
            String clearPort = findPort(model, r, Access.W1C);
            if (clearPort != null) {
                sb.append("    /* atomic clear via ").append(clearPort).append(" (write-one-to-clear) */\n");
                sb.append("    ").append(r.widthBits() > 32 ? pfx + "_bus_write64(" : pfx + "_bus_write32(")
                        .append(pfx.toUpperCase()).append("_").append(Naming.upper(clearPort)).append("_ADDR, ")
                        .append(wide64(r)).append("mask);\n");
            } else {
                sb.append("    /* read-modify-write clear (single bus entry: clear) */\n");
                sb.append("    ").append(wide ? "uint64_t" : "uint32_t").append(" cur = ")
                        .append(pfx).append("_").append(sn).append("_read();\n");
                sb.append("    ").append(pfx).append("_").append(sn).append("_write(cur & (")
                        .append(wide ? "~mask" : "(uint32_t)~mask").append("));\n");
            }
            sb.append("}\n\n");
        }
        return sb.toString();
    }

    private static String wide64(Register r) {
        return r.widthBits() > 32 ? "" : "(uint32_t)";
    }

    private static boolean policyOnlyW1S(Register r) {
        return r.isAlias() && r.fields().isEmpty() && r.access() == Access.W1S;
    }

    private static boolean policyOnlyW1C(Register r) {
        return r.isAlias() && r.fields().isEmpty() && r.access() == Access.W1C;
    }

    /** Finds an alias exposing the given atomic port policy at a distinct bus address.
     *  Aliases that share the primary's address cannot be distinguished by bus hooks,
     *  in which case callers use the single-entry read-modify-write path. */
    static String findPort(Model model, Register r, Access policy) {
        for (Register a : model.registers()) {
            if (a.isAlias() && a.aliasOf().equals(r.name()) && a.access() == policy
                    && a.fields().isEmpty() && a.address() != r.address()) {
                return a.name();
            }
        }
        return null;
    }
}
