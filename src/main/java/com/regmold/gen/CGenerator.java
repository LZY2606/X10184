package com.regmold.gen;

import com.regmold.domain.Access;
import com.regmold.domain.FieldModel;
import com.regmold.domain.Model;
import com.regmold.domain.RegisterModel;
import com.regmold.validate.ModelIndex;

import java.util.Comparator;
import java.util.List;

public class CGenerator {

    public void generate(GenResult result, Model model) {
        ModelIndex index = new ModelIndex(model);
        String hash = result.semanticHash;
        String guard = "REGMOLD_" + Names.shout(model.name) + "_H";
        StringBuilder h = new StringBuilder();
        StringBuilder c = new StringBuilder();

        banner(h, model, hash);
        h.append("#ifndef ").append(guard).append("\n#define ").append(guard).append("\n\n")
                .append("#include <stdint.h>\n\n");
        h.append("#define RM_MODEL_SEMANTIC_HASH \"").append(hash).append("\"\n");
        h.append("#define RM_DATA_WIDTH ").append(model.dataWidth).append("u\n");
        h.append("#define RM_ENDIANNESS \"").append(model.endianness).append("\"\n\n");
        busStruct(h);
        constants(h, model, index);
        declarations(h, model, index);
        h.append("#endif /* ").append(guard).append(" */\n");

        banner(c, model, hash);
        c.append("#include \"register_model.h\"\n\n");
        implementation(c, model, index, hash);

        result.files.put("register_model.h", h.toString());
        result.files.put("register_model.c", c.toString());
    }

    private void banner(StringBuilder out, Model model, String hash) {
        out.append("/*\n")
                .append(" * Generated by Register Mold - do not edit by hand.\n")
                .append(" * model: ").append(model.name).append('\n')
                .append(" * semantic-hash: ").append(hash).append('\n')
                .append(" * Each mask and write sequence below traces to this model version.\n")
                .append(" */\n");
    }

    private void busStruct(StringBuilder out) {
        out.append("typedef struct rm_bus {\n")
                .append("    void *ctx;\n")
                .append("    uint64_t (*read)(void *ctx, uint64_t offset, unsigned word);\n")
                .append("    uint64_t (*peek)(void *ctx, uint64_t offset, unsigned word); /* debug: must not consume RC bits */\n")
                .append("    void (*write)(void *ctx, uint64_t offset, unsigned word, uint64_t value);\n")
                .append("} rm_bus_t;\n\n");
    }

    private void constants(StringBuilder out, Model model, ModelIndex index) {
        for (RegisterModel r : sorted(model)) {
            int width = index.width(r);
            String pfx = "RM_" + Names.shout(model.name) + "_" + Names.shout(r.name);
            out.append("#define ").append(pfx).append("_OFFSET UINT64_C(0x")
                    .append(Long.toUnsignedString(r.offset, 16)).append(")\n");
            out.append("#define ").append(pfx).append("_RESET UINT64_C(0x")
                    .append(Long.toUnsignedString(resetOf(r), 16)).append(")\n");
            out.append("#define ").append(pfx).append("_WIDTH ").append(width).append("\n");
            for (FieldModel f : r.fields) {
                String fpfx = pfx + "_" + Names.shout(f.name);
                out.append("#define ").append(fpfx).append("_MASK UINT64_C(0x")
                        .append(Long.toUnsignedString(f.linearMask(), 16)).append(")\n");
                out.append("#define ").append(fpfx).append("_POS ").append(f.bitStart).append("\n");
                out.append("#define ").append(fpfx).append("_FIELD_WIDTH ").append(f.bitCount).append("\n");
                out.append("#define ").append(fpfx).append("_ACCESS \"").append(f.access.name()).append("\"\n");
            }
            out.append('\n');
        }
    }

    private void declarations(StringBuilder out, Model model, ModelIndex index) {
        String mod = Names.cIdent(model.name);
        for (RegisterModel r : sorted(model)) {
            String rn = mod + "_" + Names.cIdent(r.name);
            int width = index.width(r);
            String type = Names.cType(width);
            if (r.aliasOf != null) {
                out.append("void ").append(rn)
                        .append("(const rm_bus_t *bus, uint64_t value); /* atomic ")
                        .append(r.aliasWrite).append(" alias of ").append(Names.cIdent(r.aliasOf)).append(" */\n\n");
                continue;
            }
            out.append(type).append(" ").append(rn).append("_read(const rm_bus_t *bus);\n");
            out.append(type).append(" ").append(rn)
                    .append("_peek(const rm_bus_t *bus); /* debug only: consumes no read-clear bits */\n");
            out.append("void ").append(rn).append("_write(const rm_bus_t *bus, uint64_t value);\n");
            for (FieldModel f : r.fields) {
                String fn = rn + "_" + Names.cIdent(f.name);
                out.append("uint64_t ").append(fn).append("_get(uint64_t reg);\n");
                if (f.access.writableByNormalStore()) {
                    out.append("uint64_t ").append(fn).append("_set(uint64_t reg, uint64_t value);\n");
                }
            }
            out.append('\n');
        }
    }

    private void implementation(StringBuilder out, Model model, ModelIndex index, String hash) {
        String mod = Names.cIdent(model.name);
        for (RegisterModel r : sorted(model)) {
            String rn = mod + "_" + Names.cIdent(r.name);
            int width = index.width(r);
            String type = Names.cType(width);
            String define = "RM_" + Names.shout(model.name) + "_" + Names.shout(r.name);
            int words = Math.max(1, width / model.dataWidth);

            if (r.aliasOf != null) {
                out.append("/* ").append(hash).append(" atomic ").append(r.aliasWrite).append(" entry */\n");
                out.append("void ").append(rn).append("(const rm_bus_t *bus, uint64_t value)\n{\n");
                out.append("    (void)value;\n");
                out.append("    bus->write(bus->ctx, ").append(define).append("_OFFSET, 0u, value);\n");
                out.append("}\n\n");
                continue;
            }

            for (String variant : List.of("read", "peek")) {
                boolean peek = variant.equals("peek");
                String accessor = peek ? "peek" : "read";
                out.append("/* ").append(hash).append(" ").append(peek ? "debug preview (never consumes RC)" : "bus read")
                        .append(words > 1 ? "; word order " + wordOrder(model, r) : "").append(" */\n");
                out.append(type).append(' ').append(rn).append('_').append(variant).append("(const rm_bus_t *bus)\n{\n");
                if (words == 1) {
                    out.append("    return (").append(type).append(") bus->").append(accessor).append("(bus->ctx, ")
                            .append(define).append("_OFFSET, 0u);\n");
                } else {
                    out.append("    uint64_t value = 0;\n");
                    boolean little = isLittle(model, r);
                    for (int i = 0; i < words; i++) {
                        int wi = little ? i : words - 1 - i;
                        out.append("    value |= bus->").append(accessor).append("(bus->ctx, ").append(define).append("_OFFSET, ")
                                .append(wi).append("u) << ").append(wi * model.dataWidth).append(";\n");
                    }
                    out.append("    return (").append(type).append(") value;\n");
                }
                out.append("}\n\n");
            }

            out.append("/* ").append(hash).append(" write sequence");
            if (words > 1) {
                out.append("; ").append(wordOrder(model, r)).append(", last word commits");
            }
            out.append(" */\n");
            out.append("void ").append(rn).append("_write(const rm_bus_t *bus, uint64_t value)\n{\n");
            if (words == 1) {
                long reserved = 0L;
                long writable = 0L;
                for (FieldModel f : r.fields) {
                    if (f.access == Access.RESERVED) {
                        reserved |= f.linearMask();
                    } else if (f.access.writableByNormalStore()) {
                        writable |= f.linearMask();
                    }
                }
                if (reserved != 0) {
                    out.append("    uint64_t held = bus->read(bus->ctx, ").append(define).append("_OFFSET, 0u);\n");
                    out.append("    value = (value & UINT64_C(0x").append(Long.toUnsignedString(writable, 16))
                            .append(")) | (held & UINT64_C(0x").append(Long.toUnsignedString(reserved, 16))
                            .append(")); /* reserved bits written back from read value */\n");
                }
                out.append("    bus->write(bus->ctx, ").append(define).append("_OFFSET, 0u, value);\n");
            } else {
                boolean little = isLittle(model, r);
                for (int i = 0; i < words; i++) {
                    int wi = little ? i : words - 1 - i;
                    out.append("    bus->write(bus->ctx, ").append(define).append("_OFFSET, ").append(wi)
                            .append("u, (value >> ").append(wi * model.dataWidth).append(") & UINT64_C(0x")
                            .append(Long.toUnsignedString(index.fullMask(model.dataWidth), 16)).append("));\n");
                }
            }
            out.append("}\n\n");

            for (FieldModel f : r.fields) {
                String fn = rn + "_" + Names.cIdent(f.name);
                out.append("/* ").append(hash).append(" mask 0x")
                        .append(Long.toUnsignedString(f.linearMask(), 16)).append(" */\n");
                out.append("uint64_t ").append(fn).append("_get(uint64_t reg)\n{\n");
                out.append("    return (reg & UINT64_C(0x").append(Long.toUnsignedString(f.linearMask(), 16))
                        .append(")) >> ").append(f.bitStart).append(";\n}\n");
                if (f.access.writableByNormalStore()) {
                    out.append("uint64_t ").append(fn).append("_set(uint64_t reg, uint64_t value)\n{\n");
                    if (f.access == Access.W1C) {
                        out.append("    return reg & ~((value & UINT64_C(0x")
                                .append(Long.toUnsignedString(index.fullMask(f.bitCount), 16))
                                .append(")) << ").append(f.bitStart).append(");\n");
                    } else if (f.access == Access.W1S) {
                        out.append("    return reg | ((value & UINT64_C(0x")
                                .append(Long.toUnsignedString(index.fullMask(f.bitCount), 16))
                                .append(")) << ").append(f.bitStart).append(");\n");
                    } else {
                        out.append("    return (reg & ~UINT64_C(0x").append(Long.toUnsignedString(f.linearMask(), 16))
                                .append(")) | ((value << ").append(f.bitStart).append(") & UINT64_C(0x")
                                .append(Long.toUnsignedString(f.linearMask(), 16)).append("));\n");
                    }
                    out.append("}\n");
                }
            }
            out.append('\n');
        }
    }

    private boolean isLittle(Model model, RegisterModel r) {
        return !"big".equals(r.endianness != null ? r.endianness : model.endianness);
    }

    private String wordOrder(Model model, RegisterModel r) {
        return isLittle(model, r) ? "low word first" : "high word first";
    }

    private long resetOf(RegisterModel r) {
        if (r.reset != null) {
            return r.reset;
        }
        long v = 0L;
        for (FieldModel f : r.fields) {
            v |= f.reset & f.linearMask();
        }
        return v;
    }

    private List<RegisterModel> sorted(Model model) {
        return model.registers.stream().sorted(Comparator.comparing(a -> a.name)).toList();
    }
}
