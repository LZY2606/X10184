package com.regmold.gen;

import com.regmold.domain.Access;
import com.regmold.domain.FieldModel;
import com.regmold.domain.Model;
import com.regmold.domain.RegisterModel;
import com.regmold.validate.ModelIndex;

import java.util.Comparator;

public class RustGenerator {

    public void generate(GenResult result, Model model) {
        ModelIndex index = new ModelIndex(model);
        StringBuilder out = new StringBuilder();
        out.append("// Generated by Register Mold.\n")
                .append("// model: ").append(model.name).append('\n')
                .append("// semantic-hash: ").append(result.semanticHash).append('\n')
                .append("// Deterministic output: identical semantics produce identical files.\n\n");
        out.append("pub const DATA_WIDTH: u32 = ").append(model.dataWidth).append(";\n");
        out.append("pub const ENDIANNESS: &str = \"").append(model.endianness).append("\";\n\n");

        out.append("pub trait Bus {\n")
                .append("    fn read(&mut self, offset: u64, word: u32) -> u64;\n")
                .append("    /// Debug preview; implementations must not consume read-clear bits.\n")
                .append("    fn peek(&mut self, offset: u64, word: u32) -> u64;\n")
                .append("    fn write(&mut self, offset: u64, word: u32, value: u64);\n")
                .append("}\n\n");

        for (RegisterModel r : sorted(model)) {
            int width = index.width(r);
            String rn = Names.snake(r.name);
            String pfx = shout(model, r);
            out.append("/// semantic-hash: ").append(result.semanticHash).append('\n');
            out.append("pub mod ").append(rn).append(" {\n");
            out.append("    pub const OFFSET: u64 = 0x").append(Long.toUnsignedString(r.offset, 16)).append(";\n");
            out.append("    pub const RESET: u64 = 0x").append(Long.toUnsignedString(resetOf(r), 16)).append(";\n");
            out.append("    pub const WIDTH: u32 = ").append(width).append(";\n");
            for (FieldModel f : r.fields) {
                String fn = Names.snake(f.name);
                out.append("    pub mod ").append(fn).append(" {\n");
                out.append("        pub const POS: u32 = ").append(f.bitStart).append(";\n");
                out.append("        pub const WIDTH: u32 = ").append(f.bitCount).append(";\n");
                out.append("        pub const MASK: u64 = 0x")
                        .append(Long.toUnsignedString(f.linearMask(), 16)).append(";\n");
                out.append("        pub const ACCESS: &str = \"").append(f.access.name()).append("\";\n");
                out.append("        pub fn get(reg: u64) -> u64 {\n");
                out.append("            (reg & MASK) >> POS\n        }\n");
                if (f.access.writableByNormalStore()) {
                    if (f.access == Access.W1C) {
                        out.append("        pub fn clear(reg: u64, value: u64) -> u64 {\n");
                        out.append("            reg & !((value & ((1u64 << WIDTH) - 1)) << POS)\n        }\n");
                    } else if (f.access == Access.W1S) {
                        out.append("        pub fn set(reg: u64, value: u64) -> u64 {\n");
                        out.append("            reg | ((value & ((1u64 << WIDTH) - 1)) << POS)\n        }\n");
                    } else {
                        out.append("        pub fn set(reg: u64, value: u64) -> u64 {\n");
                        out.append("            (reg & !MASK) | ((value << POS) & MASK)\n        }\n");
                    }
                }
                out.append("    }\n");
            }
            boolean multi = width > model.dataWidth;
            if (r.aliasOf != null) {
                out.append("    /// Atomic `").append(r.aliasWrite).append("` alias of `")
                        .append(Names.snake(r.aliasOf)).append("`.\n");
                out.append("    pub fn write_alias<B: super::Bus>(bus: &mut B, value: u64) {\n");
                out.append("        bus.write(OFFSET, 0, value);\n    }\n");
            } else {
                out.append("    /// Bus read (consumes read-clear bits).\n");
                out.append("    pub fn read<B: super::Bus>(bus: &mut B) -> u64 {\n");
                readBody(out, model, r, index, false);
                out.append("    }\n");
                out.append("    /// Debug preview that must never consume read-clear bits.\n");
                out.append("    pub fn peek<B: super::Bus>(bus: &mut B) -> u64 {\n");
                readBody(out, model, r, index, true);
                out.append("    }\n");
                out.append("    pub fn write<B: super::Bus>(bus: &mut B, value: u64) {\n");
                writeBody(out, model, r, index);
                out.append("    }\n");
                if (multi) {
                    out.append("    // Multi-word word order: ")
                            .append("big".equals(r.endianness != null ? r.endianness : model.endianness)
                                    ? "high word first"
                                    : "low word first; final word commits")
                            .append(".\n");
                }
            }
            out.append("}\n\n");
        }
        result.files.put("register_model.rs", out.toString());
    }

    private void readBody(StringBuilder out, Model model, RegisterModel r, ModelIndex index, boolean peek) {
        int width = index.width(r);
        int words = Math.max(1, width / model.dataWidth);
        String accessor = peek ? "peek" : "read";
        if (words == 1) {
            out.append("        bus.").append(accessor).append("(OFFSET, 0)\n");
        } else {
            boolean little = !"big".equals(r.endianness != null ? r.endianness : model.endianness);
            out.append("        let mut value: u64 = 0;\n");
            for (int i = 0; i < words; i++) {
                int wi = little ? i : words - 1 - i;
                out.append("        value |= bus.").append(accessor).append("(OFFSET, ").append(wi)
                        .append(") << ").append(wi * model.dataWidth).append(";\n");
            }
            out.append("        value\n");
        }
    }

    private void writeBody(StringBuilder out, Model model, RegisterModel r, ModelIndex index) {
        int width = index.width(r);
        int words = Math.max(1, width / model.dataWidth);
        if (words == 1) {
            long reserved = 0L;
            long writable = 0L;
            for (FieldModel f : r.fields) {
                if (f.access == Access.RESERVED) {
                    reserved |= f.linearMask();
                } else if (f.access.writableByNormalStore()) {
                    writable |= f.linearMask();
                }
            }
            if (reserved != 0) {
                out.append("        let held = bus.read(OFFSET, 0);\n");
                out.append("        let value = (value & 0x")
                        .append(Long.toUnsignedString(writable, 16))
                        .append(") | (held & 0x").append(Long.toUnsignedString(reserved, 16)).append(");\n");
            }
            out.append("        bus.write(OFFSET, 0, value);\n");
        } else {
            boolean little = !"big".equals(r.endianness != null ? r.endianness : model.endianness);
            int count = words;
            for (int i = 0; i < count; i++) {
                int wi = little ? i : count - 1 - i;
                out.append("        bus.write(OFFSET, ").append(wi).append(", (value >> ")
                        .append(wi * model.dataWidth).append(") & 0x")
                        .append(Long.toUnsignedString(index.fullMask(model.dataWidth), 16)).append(");\n");
            }
        }
    }

    private String shout(Model model, RegisterModel r) {
        return Names.shout(model.name) + "_" + Names.shout(r.name);
    }

    private long resetOf(RegisterModel r) {
        if (r.reset != null) {
            return r.reset;
        }
        long v = 0L;
        for (FieldModel f : r.fields) {
            v |= f.reset & f.linearMask();
        }
        return v;
    }

    private java.util.List<RegisterModel> sorted(Model model) {
        return model.registers.stream().sorted(Comparator.comparing(a -> a.name)).toList();
    }
}
