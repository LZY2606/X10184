package com.regmold.gen;

import com.regmold.domain.Access;
import com.regmold.domain.Field;
import com.regmold.domain.Model;
import com.regmold.domain.Register;

import java.util.List;

/** Generates a dependency-free Rust module (rustc --edition 2021 compatible). */
public final class RustGenerator {

    private RustGenerator() {
    }

    public static List<GenFile> generate(Model model, String modelHash) {
        String pfx = Naming.snake(model.name());
        return List.of(new GenFile("rust/" + pfx + "_regs.rs", body(model, pfx, modelHash)));
    }

    private static String body(Model model, String pfx, String hash) {
        String modName = pfx + "_regs";
        StringBuilder sb = new StringBuilder();
        sb.append("//! ").append(model.name()).append(" register access layer\n");
        sb.append("//!\n//! Generated by register-mold. DO NOT EDIT.\n");
        sb.append("//! model: ").append(model.name()).append(" version ").append(model.version()).append("\n");
        sb.append("//! sha256: ").append(hash).append("\n");
        sb.append("//! revision: ").append(model.revisionId()).append("\n\n");
        sb.append("#![allow(dead_code, non_upper_case_globals)]\n\n");
        sb.append("pub const MODEL_HASH: &str = \"").append(hash).append("\";\n");
        sb.append("pub const MODEL_VERSION: &str = \"").append(model.version()).append("\";\n");
        sb.append("pub const WORD_BYTES: usize = ").append(model.wordBytes()).append(";\n\n");

        sb.append("/// Platform bus hooks implemented by the embedding system.\n");
        sb.append("pub trait BusHooks {\n");
        sb.append("    fn read32(&self, addr: u64) -> u32;\n");
        sb.append("    fn write32(&self, addr: u64, data: u32);\n");
        sb.append("    fn read64(&self, addr: u64) -> u64;\n");
        sb.append("    fn write64(&self, addr: u64, data: u64);\n");
        sb.append("}\n\n");

        for (Register r : model.registers()) {
            String modR = Naming.snake(r.name());
            sb.append("/// ").append(r.name()).append(" @ 0x")
                    .append(Long.toUnsignedString(r.address(), 16));
            if (r.isAlias()) {
                sb.append(" (alias of ").append(r.aliasOf()).append(")");
            }
            sb.append("\n");
            sb.append("pub mod ").append(modR).append(" {\n");
            sb.append("    pub const ADDR: u64 = 0x").append(Long.toUnsignedString(r.address(), 16)).append(";\n");
            sb.append("    pub const WIDTH_BITS: u32 = ").append(r.widthBits()).append(";\n");
            for (Field f : r.fields()) {
                sb.append("    pub mod ").append(Naming.snake(f.name())).append(" {\n");
                sb.append("        pub const SHIFT: u32 = ").append(f.lsb()).append(";\n");
                sb.append("        pub const WIDTH: u32 = ").append(f.width()).append(";\n");
                sb.append("        pub const MASK: u64 = 0x").append(Long.toUnsignedString(f.mask(), 16)).append(";\n");
                sb.append("        pub const RESET: u64 = 0x").append(Long.toUnsignedString(f.reset(), 16)).append(";\n");
                sb.append("    }\n");
            }
            boolean wide = r.widthBits() > 32;
            sb.append("    pub fn read<H: super::BusHooks>(bus: &H) -> ").append(wide ? "u64" : "u32").append(" {\n");
            sb.append("        bus.").append(wide ? "read64" : "read32").append("(ADDR)\n    }\n");
            sb.append("    pub fn write<H: super::BusHooks>(bus: &H, value: ")
                    .append(wide ? "u64" : "u32").append(") {\n");
            sb.append("        bus.").append(wide ? "write64" : "write32").append("(ADDR, value);\n    }\n");
            String setPort = CGenerator.findPort(model, r, Access.W1S);
            String clearPort = CGenerator.findPort(model, r, Access.W1C);
            appendMaskOp(sb, r, "set", setPort, true, wide);
            appendMaskOp(sb, r, "clear", clearPort, false, wide);
            sb.append("}\n\n");
        }
        sb.append("/// Marker for module identity: ").append(modName).append("\n");
        return sb.toString();
    }

    private static void appendMaskOp(StringBuilder sb, Register r, String op, String port,
                                     boolean isSet, boolean wide) {
        sb.append("    pub fn ").append(op).append("<H: super::BusHooks>(bus: &H, mask: u64) {\n");
        if (port != null) {
            sb.append("        // atomic ").append(isSet ? "write-one-to-set via " : "write-one-to-clear via ")
                    .append(port).append("\n");
            if (wide) {
                sb.append("        bus.write64(").append(Naming.snake(port)).append("::ADDR, mask);\n");
            } else {
                sb.append("        bus.write32(").append(Naming.snake(port)).append("::ADDR, mask as u32);\n");
            }
        } else {
            sb.append("        // single-entry read-modify-write ").append(op).append("\n");
            if (wide) {
                sb.append("        let cur = bus.read64(ADDR);\n");
                sb.append("        bus.write64(ADDR, cur ").append(isSet ? "|" : "&").append(" ");
                sb.append(isSet ? "mask" : "!mask").append(");\n");
            } else {
                sb.append("        let cur = bus.read32(ADDR);\n");
                sb.append("        bus.write32(ADDR, cur ").append(isSet ? "|" : "&").append(" ");
                sb.append(isSet ? "(mask as u32))" : "!(mask as u32))").append(";\n");
            }
        }
        sb.append("    }\n");
    }
}
